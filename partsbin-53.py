def show_help():
    print("PartsBin - Parts and Supplies Bin Tracker")
    print("=" * 40)
    print("Usage:")
    print("  python partsbin.py <command> [options]")
    print()
    print("Commands:")
    print("  add        Add a new part to the bin")
    print("  list       List all parts with quantities")
    print("  check      Show parts below their reorder point")
    print("  reorder    List parts that need reordering")
    print("  delete     Remove a part from the bin")
    print("  help       Show this help message")
    print()
    print("Options:")
    print("  --help     Show this help message and exit")
    print("  --version  Show the current version and exit")
    print()
    print("Examples:")
    print("  python partsbin.py add 'Screw M4' 100 5 001")
    print("  python partsbin.py list")
    print("  python partsbin.py check")
    print("  python partsbin.py delete 'Screw M4'")
